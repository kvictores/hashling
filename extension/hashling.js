  /** Browser-safe URL for a pixel art file: chrome.runtime.getURL inside the extension (also in injected Shadow DOM), relative path otherwise. */
  function assetUrl(file) {
    var path = 'assets/hashling/pixel/' + file + '.png';
    try {
      if (root.chrome && root.chrome.runtime && root.chrome.runtime.getURL) return root.chrome.runtime.getURL(path);
    } catch (e) { /* fall through */ }
    return path;
  }
  function wearUrl(file) { return assetUrl('wearables/' + file); }
  function n2(v) { return (Math.round(v * 100) / 100).toString(); }
  var PIX = ' style="image-rendering:pixelated"';
  var FUR_SUFFIX = { fur_moss: '-moss', fur_amber: '-amber', fur_cyan: '-cyan' };
  /** happy -> happy sprite, sleepy -> sleep sprite, sad/alert -> idle (no dedicated sprites: motion + labelled cue). */
  function moodKey(mood) { return mood === 'happy' ? 'happy' : mood === 'sleepy' ? 'sleep' : 'idle'; }

  // Same maths as geometry.ts
  function placement(stage, mood, fur) {
    var st = PET_GEOM.stages[stage] || PET_GEOM.stages.cub;
    var CANVAS = PET_GEOM.canvas, GROUND = PET_GEOM.ground;
    var sp = stage === 'egg' ? st : st.moods[moodKey(mood)];
    var k = st.scale, bb = sp.bbox;
    var x = CANVAS / 2 - k * ((bb[0] + bb[2]) / 2);
    var y = GROUND - k * bb[3];
    var file = stage === 'egg' ? sp.file : sp.file + (FUR_SUFFIX[fur] || '');
    var anchors = null;
    if (sp.anchors) {
      anchors = {};
      Object.keys(sp.anchors).forEach(function (name) {
        var a = sp.anchors[name];
        anchors[name] = { x: x + k * a.x, y: y + k * a.y, unit: k * a.s, rot: a.r };
      });
    }
    return { file: file, x: x, y: y, w: sp.width * k, h: sp.height * k, anchors: anchors };
  }

  function anchorTransform(a) {
    return 'translate(' + a.x.toFixed(2) + ' ' + a.y.toFixed(2) + ') rotate(' + a.rot + ') scale(' + a.unit.toFixed(4) + ')';
  }

  /** Same maths as geometry.ts: transform that lands a wearable PNG (drawn at 0,0,width,height) on the pet. */
  function mountOf(w, stage, mood) {
    var m = {};
    Object.keys(w.mount).forEach(function (k) { m[k] = w.mount[k]; });
    [w.mount.byStage && w.mount.byStage[stage], w.mount.byPose && w.mount.byPose[stage + '-' + moodKey(mood)]].forEach(function (o) {
      if (o) Object.keys(o).forEach(function (k) { m[k] = o[k]; });
    });
    return m;
  }
  function wearTransform(w, stage, anchors, mood) {
    var m = mountOf(w, stage, mood), o = null;
    if (m.span) {
      var a = anchors[m.span[0]], b = anchors[m.span[1]];
      if (!a || !b) return null;
      var dx = b.x - a.x, dy = b.y - a.y;
      o = { x: (a.x + b.x) / 2, y: (a.y + b.y) / 2, unit: Math.sqrt(dx * dx + dy * dy) / 100, rot: Math.atan2(dy, dx) * 180 / Math.PI };
    } else o = anchors[m.anchor];
    if (!o) return null;
    var ab = w.alphaBounds, aw = ab[2] - ab[0], ah = ab[3] - ab[1], k = m.w / aw;
    var px = ab[0] + m.at[0] * aw, py = ab[1] + m.at[1] * ah;
    return 'translate(' + o.x.toFixed(2) + ' ' + o.y.toFixed(2) + ') rotate(' + (o.rot + (m.rot || 0)).toFixed(2) + ') scale(' + o.unit.toFixed(4) +
      ') translate(' + m.dx + ' ' + m.dy + ') scale(' + k.toFixed(5) + ') translate(' + (-px).toFixed(1) + ' ' + (-py).toFixed(1) + ')';
  }

  /** All wearables of one registry layer, as pixelated PNG <image> layers. Mirrors items.tsx. */
  function wearLayer(layer, eq, stage, mood, anchors, uid) {
    if (!anchors) return ''; // egg: no gear
    var out = '';
    [eq.accessory, eq.collar, eq.hat].forEach(function (id) {
      var w = id && WEAR_REG.wearables[id];
      if (!w || w.layer !== layer) return;
      var t = wearTransform(w, stage, anchors, mood);
      if (!t) return;
      var m = mountOf(w, stage, mood), fade = m.mask, ab = w.alphaBounds, k = uid + '-' + id, defs = '', attrs = '';
      if (fade) {
        defs += '<linearGradient id="' + k + '-g" gradientUnits="userSpaceOnUse" x1="' + ab[0] + '" x2="' + ab[2] + '" y1="0" y2="0"><stop offset="0" stop-color="#000"/><stop offset="' + fade + '" stop-color="#fff"/><stop offset="' + (1 - fade) + '" stop-color="#fff"/><stop offset="1" stop-color="#000"/></linearGradient>' +
          '<mask id="' + k + '-m" maskUnits="userSpaceOnUse" x="0" y="0" width="' + w.width + '" height="' + w.height + '"><rect width="' + w.width + '" height="' + w.height + '" fill="url(#' + k + '-g)"/></mask>';
        attrs += ' mask="url(#' + k + '-m)"';
      }
      if (w.crop) {
        var cx = ab[0] + w.crop[0] * (ab[2] - ab[0]), cy = ab[1] + w.crop[1] * (ab[3] - ab[1]);
        defs += '<clipPath id="' + k + '-c"><rect x="' + cx + '" y="' + cy + '" width="' + ((w.crop[2] - w.crop[0]) * (ab[2] - ab[0])) + '" height="' + (((w.crop[3] - w.crop[1]) * (ab[3] - ab[1])) + 1) + '"/></clipPath>';
        attrs += ' clip-path="url(#' + k + '-c)"';
      }
      out += '<g data-wearable="' + id + '" transform="' + t + '">' + (defs ? '<defs>' + defs + '</defs>' : '') +
        '<image href="' + wearUrl(w.file) + '" xlink:href="' + wearUrl(w.file) + '" x="0" y="0" width="' + w.width + '" height="' + w.height + '" aria-hidden="true"' + PIX + attrs + '/></g>';
    });
    return out;
  }

  function cue(mood, at, anim) {
    if (mood === 'happy') return '';
    var inner = '';
    if (mood === 'alert') {
      inner = '<g' + (anim ? ' class="hl-cue-pop"' : '') + '><circle r="9.5" fill="#D9463B" stroke="#fff" stroke-width="2"/>' +
        '<rect x="-1.5" y="-5.6" width="3" height="7" rx="1.5" fill="#fff"/><circle cy="4.6" r="1.7" fill="#fff"/></g>';
    } else if (mood === 'sad') {
      inner = '<g' + (anim ? ' class="hl-cue-pop"' : '') + '><path d="M0 -10 C6 -2 8 2 8 5 A8 8 0 0 1 -8 5 C-8 2 -6 -2 0 -10Z" fill="#7FC4E0" stroke="#fff" stroke-width="1.6" stroke-linejoin="round"/>' +
        '<path d="M-3.4 3 A4 4 0 0 0 -1.2 7.2" fill="none" stroke="#fff" stroke-width="1.5" stroke-linecap="round" opacity=".85"/></g>';
    } else if (mood === 'sleepy') {
      inner = '<g fill="#52675E" font-family="Georgia, serif" font-weight="700" stroke="#FFFEF9" stroke-width=".8" paint-order="stroke">' +
        '<text x="-2" y="4" font-size="16"' + (anim ? ' class="hl-z"' : '') + '>z</text>' +
        '<text x="8" y="-8" font-size="11"' + (anim ? ' class="hl-z hl-z2"' : '') + '>z</text></g>';
    }
    return '<g transform="translate(' + at.x.toFixed(1) + ' ' + at.y.toFixed(1) + ')" aria-hidden="true">' + inner + '</g>';
  }

  function build(opts) {
    opts = opts || {};
    var stage = PET_GEOM.stages[opts.stage] ? opts.stage : 'egg';
    var mood = opts.mood || 'happy';
    var eq = opts.equipped || {};
    var size = opts.size || 120;
    var anim = opts.animated !== false;
    var uid = 'hl' + (++uidCounter) + Math.random().toString(36).slice(2, 6);
    var label = 'Hashling the ' + (stage === 'egg' ? 'egg' : 'snow-leopard ' + stage) + ', feeling ' + mood;
    var pl = placement(stage, mood, eq.fur);
    var a = pl.anchors, GROUND = PET_GEOM.ground;

    var bodyClass = '';
    if (anim) {
      if (stage === 'egg') bodyClass = mood === 'alert' ? 'hl-shake' : mood === 'sleepy' ? 'hl-breathe-slow' : 'hl-wobble';
      else if (mood === 'alert') bodyClass = 'hl-alert-bob'; // no alert sprite: same stage + gear, restrained bob + labelled warning badge
      else bodyClass = mood === 'sleepy' ? 'hl-breathe-slow' : mood === 'sad' ? 'hl-sad-sway' : 'hl-breathe';
    }
    var pivot = 'translate(100 ' + GROUND + ') ', unpivot = ' translate(-100 -' + GROUND + ')';
    var pose = '';
    if (stage !== 'egg') {
      if (mood === 'sad') pose = pivot + 'scale(1 0.965)' + unpivot;
      else if (mood === 'sleepy') pose = pivot + 'scale(1 0.985)' + unpivot;
    }
    var tone = mood === 'sad' ? 'saturate(0.82) brightness(0.97)' : mood === 'sleepy' ? 'brightness(0.97) saturate(0.95)' : '';
    var cueAt = a ? { x: a.crown.x + 31, y: a.crown.y - 3 } : { x: 154, y: 58 };
    var shadowRx = stage === 'egg' ? 40 : stage === 'kitten' ? 48 : stage === 'cub' ? 54 : 62;

    var s = '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 200 200" width="' + size + '" height="' + size +
      '" role="img" aria-label="' + label + (mood === 'alert' ? ', on alert: warning' : '') + '" style="overflow:visible">' + STYLE +
      '<defs><radialGradient id="' + uid + '-sh" cx="50%" cy="50%" r="50%"><stop offset="0%" stop-color="#1F3D2F" stop-opacity=".32"/><stop offset="100%" stop-color="#1F3D2F" stop-opacity="0"/></radialGradient></defs>' +
      '<ellipse cx="100" cy="' + (GROUND + 1) + '" rx="' + shadowRx + '" ry="6.5" fill="url(#' + uid + '-sh)"/>' +
      '<g' + (bodyClass ? ' class="' + bodyClass + '"' : '') + '><g' + (pose ? ' transform="' + pose + '"' : '') + '><g' + (tone ? ' style="filter:' + tone + '"' : '') + '>' +
      wearLayer('behindPet', eq, stage, mood, a, uid) +
      '<image href="' + assetUrl(pl.file) + '" xlink:href="' + assetUrl(pl.file) + '" x="' + n2(pl.x) + '" y="' + n2(pl.y) + '" width="' + n2(pl.w) + '" height="' + n2(pl.h) + '" preserveAspectRatio="xMidYMid meet" aria-hidden="true"' + PIX + '/>' +
      wearLayer('frontStraps', eq, stage, mood, a, uid) + wearLayer('frontAccessory', eq, stage, mood, a, uid) + wearLayer('collar', eq, stage, mood, a, uid) + wearLayer('hat', eq, stage, mood, a, uid) +
      '</g></g></g>' + cue(mood, cueAt, anim) + '</svg>';
    return s;
  }

  root.HashlingSVG = { build: build, FUR: FUR, LINE: LINE, assetUrl: assetUrl };
