"""Copy Hashling's item artwork (web/src/hashling/items.json) into extension/hashling.js.

The extension has no build step, so the same SVG fragments are embedded between two marker comments.
Run from the repo root:  python scripts/sync_items.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
items = json.loads((ROOT / "web/src/hashling/items.json").read_text(encoding="utf-8"))
items.pop("_comment", None)
target = ROOT / "extension/hashling.js"
src = target.read_text(encoding="utf-8")

block = "  // @@ITEMS-BEGIN (generated by scripts/sync_items.py from web/src/hashling/items.json; do not edit by hand)\n"
block += "  var ITEM_SVG = " + json.dumps(items, indent=2, ensure_ascii=False).replace("\n", "\n  ") + ";\n"
block += "  // @@ITEMS-END\n"

new, n = re.subn(r"  // @@ITEMS-BEGIN.*?// @@ITEMS-END\n", lambda _: block, src, flags=re.S)
if n != 1:
    raise SystemExit("Markers not found in extension/hashling.js")
target.write_text(new, encoding="utf-8")
print(f"Synced {sum(len(v) for v in items.values())} item fragments into {target.relative_to(ROOT)}")
