"""Copy Hashling's shared art data into extension/hashling.js.

The extension has no build step, so the same data the web app imports is embedded between marker comments:
  * web/src/hashling/items.json -> WEAR_REG  (wearable registry v2: PNG file, alphaBounds, layer, mount, strap svg)
  * web/src/hashling/pets.json  -> PET_GEOM  (stage/fur art files, normalisation bbox, wearable anchors)
Run from the repo root:  python scripts/sync_items.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(rel):
    data = json.loads((ROOT / rel).read_text(encoding="utf-8"))
    data.pop("_comment", None)
    return data


items = load("web/src/hashling/items.json")
pets = load("web/src/hashling/pets.json")
target = ROOT / "extension/hashling.js"
src = target.read_text(encoding="utf-8")


def js(name, data):
    return f"  var {name} = " + json.dumps(data, indent=2, ensure_ascii=False).replace("\n", "\n  ") + ";\n"


block = "  // @@ITEMS-BEGIN (generated by scripts/sync_items.py from web/src/hashling/items.json + pets.json; do not edit by hand)\n"
block += js("WEAR_REG", items) + js("PET_GEOM", pets)
block += "  // @@ITEMS-END\n"

new, n = re.subn(r"  // @@ITEMS-BEGIN.*?// @@ITEMS-END\n", lambda _: block, src, flags=re.S)
if n != 1:
    raise SystemExit("Markers not found in extension/hashling.js")
target.write_text(new, encoding="utf-8")
print(f"Synced {len(items['wearables'])} wearables + pet geometry into {target.relative_to(ROOT)}")
